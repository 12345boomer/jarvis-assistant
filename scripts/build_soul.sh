#!/usr/bin/env bash
# Build ~/.hermes/SOUL.md = SOUL.md (persona + rules) + USER.md (who Ben is).
# Hermes injects SOUL.md verbatim as the first system-prompt section (cap ~20k chars).
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HERMES_HOME="${HERMES_HOME:-$HOME/.hermes}"
OUT="$HERMES_HOME/SOUL.md"

{
  echo "<!-- GENERATED by scripts/build_soul.sh from SOUL.md + USER.md. Edit those in the repo, then run make link. -->"
  cat "$REPO/SOUL.md"
  echo
  echo "---"
  echo
  cat "$REPO/USER.md"
} > "$OUT.tmp"

size=$(wc -c < "$OUT.tmp" | tr -d ' ')
if [ "$size" -gt 19000 ]; then
  echo "  WARN    SOUL.md is $size chars; Hermes truncates around 20,000. Trim USER.md." >&2
fi
mv "$OUT.tmp" "$OUT"
echo "  built   $OUT ($size chars)"
